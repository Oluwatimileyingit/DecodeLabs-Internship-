/* 
   SECTION 1: DATABASE AND TABLE INSPECTION
   Objective: Understand the structure and size of the dataset.
    */

-- Inspect table columns and data types
DESCRIBE `project-cleaning`;

-- Count the total number of records
SELECT COUNT(*) AS total_records
FROM `project-cleaning`;

-- Preview the first 10 records
SELECT *
FROM `project-cleaning`
LIMIT 10;


/* 
   SECTION 2: DATA RETRIEVAL AND EXPLORATION
   Objective: Retrieve relevant columns and explore
   unique values in the dataset.
   */

-- Retrieve selected columns
SELECT
    OrderID,
    Product,
    Quantity,
    TotalPrice
FROM `project-cleaning`;

-- Identify the different products
SELECT DISTINCT Product
FROM `project-cleaning`;


/*
   SECTION 3: DATA FILTERING
   Objective: Filter records using WHERE and AND.
    */

-- Retrieve all chair orders
SELECT *
FROM `project-cleaning`
WHERE Product = 'Chair';

-- Retrieve delivered orders
SELECT *
FROM `project-cleaning`
WHERE OrderStatus = 'Delivered';

-- Retrieve cash payments
SELECT *
FROM `project-cleaning`
WHERE PaymentMethod = 'Cash';

-- Retrieve orders above 2,000
SELECT *
FROM `project-cleaning`
WHERE TotalPrice > 2000;

-- Retrieve delivered orders paid for with cash
SELECT *
FROM `project-cleaning`
WHERE OrderStatus = 'Delivered'
AND PaymentMethod = 'Cash';


/* 
   SECTION 4: DATA SORTING
   Objective: Arrange records in ascending or descending
   order using ORDER BY.
    */

-- Display products by highest order value
SELECT Product, TotalPrice
FROM `project-cleaning`
ORDER BY TotalPrice DESC;

-- Display orders by quantity in ascending order
SELECT Product, Quantity
FROM `project-cleaning`
ORDER BY Quantity ASC;


/*
   SECTION 5: PRODUCT PERFORMANCE ANALYSIS
   Objective: Evaluate product revenue, demand and
   average order value.
    */

-- Analyse revenue, number of orders and average order
-- value by product
SELECT
    Product,
    SUM(TotalPrice) AS total_revenue,
    COUNT(OrderID) AS number_of_orders,
    ROUND(AVG(TotalPrice), 2) AS average_order_value
FROM `project-cleaning`
GROUP BY Product
ORDER BY total_revenue DESC;

-- Analyse quantity sold and average quantity per order
SELECT
    Product,
    SUM(Quantity) AS total_quantity_sold,
    COUNT(OrderID) AS total_orders,
    ROUND(AVG(Quantity), 2) AS average_quantity_per_order
FROM `project-cleaning`
GROUP BY Product
ORDER BY total_quantity_sold DESC;


/* 
   SECTION 6: PAYMENT METHOD ANALYSIS
   Objective: Examine customer payment preferences
   and revenue generated by each payment method.
  */

SELECT
    PaymentMethod,
    COUNT(OrderID) AS total_orders,
    SUM(TotalPrice) AS total_revenue,
    ROUND(AVG(TotalPrice), 2) AS average_order_value
FROM `project-cleaning`
GROUP BY PaymentMethod
ORDER BY total_revenue DESC;


/*
   SECTION 7: ORDER STATUS ANALYSIS
   Objective: Examine the distribution of order statuses
   and their percentage contribution to all orders.
   */

SELECT
    OrderStatus,
    COUNT(*) AS total_orders,
    ROUND(
        COUNT(*) * 100.0 /
        (SELECT COUNT(*) FROM `project-cleaning`),
        2
    ) AS percentage
FROM `project-cleaning`
GROUP BY OrderStatus
ORDER BY percentage DESC;


/*
   SECTION 8: CANCELLATION ANALYSIS
   Objective: Identify products and payment methods
   associated with cancelled orders.
 */

-- Number of cancelled orders by product
SELECT
    Product,
    COUNT(*) AS cancelled_orders
FROM `project-cleaning`
WHERE OrderStatus = 'Cancelled'
GROUP BY Product
ORDER BY cancelled_orders DESC;

-- Number of cancelled orders by payment method
SELECT
    PaymentMethod,
    COUNT(*) AS cancelled_orders
FROM `project-cleaning`
WHERE OrderStatus = 'Cancelled'
GROUP BY PaymentMethod
ORDER BY cancelled_orders DESC;

-- Cancellation rate by product
SELECT
    Product,
    COUNT(*) AS total_orders,
    SUM(
        CASE
            WHEN OrderStatus = 'Cancelled' THEN 1
            ELSE 0
        END
    ) AS cancelled_orders,
    ROUND(
        SUM(
            CASE
                WHEN OrderStatus = 'Cancelled' THEN 1
                ELSE 0
            END
        ) * 100.0 / COUNT(*),
        2
    ) AS cancellation_rate
FROM `project-cleaning`
GROUP BY Product
ORDER BY cancellation_rate DESC;

-- Cancellation rate by payment method
SELECT
    PaymentMethod,
    COUNT(*) AS total_orders,
    SUM(
        CASE
            WHEN OrderStatus = 'Cancelled' THEN 1
            ELSE 0
        END
    ) AS cancelled_orders,
    ROUND(
        SUM(
            CASE
                WHEN OrderStatus = 'Cancelled' THEN 1
                ELSE 0
            END
        ) * 100.0 / COUNT(*),
        2
    ) AS cancellation_rate
FROM `project-cleaning`
GROUP BY PaymentMethod
ORDER BY cancellation_rate DESC;


/* 
   SECTION 9: REFERRAL SOURCE ANALYSIS
   Objective: Evaluate the performance of different
   referral sources based on orders and revenue.
    */

-- Analyse total orders, revenue and average order value
-- by referral source
SELECT
    ReferralSource,
    COUNT(OrderID) AS total_orders,
    SUM(TotalPrice) AS total_revenue,
    ROUND(AVG(TotalPrice), 2) AS average_order_value
FROM `project-cleaning`
GROUP BY ReferralSource
ORDER BY total_revenue DESC;


/*
   SECTION 10: DELIVERY PERFORMANCE ANALYSIS
   Objective: Evaluate delivered orders, delivered revenue
   and delivery rates across referral sources.
   */

-- Analyse delivered orders and revenue by referral source
SELECT
    ReferralSource,
    COUNT(OrderID) AS delivered_orders,
    SUM(TotalPrice) AS delivered_revenue
FROM `project-cleaning`
WHERE OrderStatus = 'Delivered'
GROUP BY ReferralSource
ORDER BY delivered_revenue DESC;

-- Calculate delivery rate by referral source
SELECT
    ReferralSource,
    COUNT(OrderID) AS total_orders,
    SUM(
        CASE
            WHEN OrderStatus = 'Delivered' THEN 1
            ELSE 0
        END
    ) AS delivered_orders,
    ROUND(
        SUM(
            CASE
                WHEN OrderStatus = 'Delivered' THEN 1
                ELSE 0
            END
        ) * 100.0 / COUNT(OrderID),
        2
    ) AS delivery_rate
FROM `project-cleaning`
GROUP BY ReferralSource
ORDER BY delivery_rate DESC;


